# --------------------------------------------------------------------------
# Number formatting helpers
# --------------------------------------------------------------------------
def fmt_radix(n: int, base: int) -> bytes:
    if n == 0:
        return b"0"
    digits = b"0123456789ABCDEF"
    out = bytearray()
    while n:
        out.append(digits[n % base])
        n //= base
    return bytes(reversed(out))


def gfa_float_to_double(b8: bytes) -> float:
    """GFA 3.x 8 byte float: sign bit dropped, 52 bit mantissa in bits 62..11,
    11 bit exponent in bits 10..0 -> rebuild an IEEE 754 double."""
    v = int.from_bytes(b8, "big")
    mant = (v & 0x7FFFFFFFFFFFF800) >> 11
    exp = v & 0x7FF
    return struct.unpack(">d", ((exp << 52) | mant).to_bytes(8, "big"))[0]


def fmt_double(d: float) -> bytes:
    """Shortest round-trip decimal text; exponent form outside 1e-4..1e15."""
    if d != d or d in (float("inf"), float("-inf")):
        return b"?"
    if d == 0:
        return b"0"
    a = abs(d)
    if 1e-4 <= a < 1e15:
        s = repr(d)
        if "e" in s or "E" in s:
            s = format(d, "f").rstrip("0").rstrip(".")
        elif s.endswith(".0"):
            s = s[:-2]
        return s.encode("ascii")
    m, _, e = ("%.17e" % d).partition("e")
    # find the shortest mantissa that round-trips
    for prec in range(0, 18):
        t = "%.*e" % (prec, d)
        if float(t) == d:
            m, _, e = t.partition("e")
            break
    sign = "-" if e[0] == "-" else "+"
    return ("%sE%s%02d" % (m.rstrip("0").rstrip(".") if "." in m else m,
                           sign, int(e[1:]))).encode("ascii")


def to_int_trunc(d: float) -> int:
    try:
        return int(d) & 0xFFFFFFFFFFFFFFFF
    except (OverflowError, ValueError):
        return 0


# --------------------------------------------------------------------------
# Header / identifier parsing
# --------------------------------------------------------------------------
class Program:
    HDR_SIZE = 164

    def __init__(self, data: bytes):
        if len(data) < self.HDR_SIZE:
            raise GfaError("file too short for a GFA 3.x header")
        self.data = data
        self.protected = data[0] == 0xFF
        self.version = data[1]
        magic = data[2:12]
        if magic[:8] == b"GfABASIC" or self.version in (1, 2):
            raise GfaError("GFA-BASIC 1.x/2.x files are not supported yet")
        if magic[:10] != b"GFA-BASIC3":
            raise GfaError("unknown magic %r (Amiga/DOS/Windows GFA files are "
                           "not supported)" % magic)
        if self.version not in (3, 4):
            raise GfaError("unsupported file version %d" % self.version)
        self.sep = list(struct.unpack(">38I", data[12:12 + 152]))
        s = self.sep
        pool_len = s[16] - s[0]
        self.pool_off = self.HDR_SIZE
        self.list_off = self.pool_off + pool_len
        self.list_len = s[19] - s[16]
        if pool_len < 0 or self.list_len < 0 or \
                self.list_off + self.list_len > len(data):
            raise GfaError("inconsistent header (truncated file?)")
        self.idents = self._read_identifiers()

    def _read_identifiers(self):
        """16 groups of pascal strings; each group padded to an even length."""
        groups = []
        pos = self.pool_off
        end = self.list_off
        for g in range(16):
            count = (self.sep[20 + g] - self.sep[19 + g]) // 4
            start = pos
            names = []
            for _ in range(count):
                if pos >= end:
                    break
                n = self.data[pos]
                raw = self.data[pos + 1:pos + 1 + n]
                pos += 1 + n
                # identifiers are stored upper case; GFA lists them lower case
                names.append(bytes(c + 32 if 0x41 <= c <= 0x5A else c
                                   for c in raw))
            if (pos - start) & 1:
                pos += 1
            groups.append(names)
        return groups

    def var_name(self, vtype: int, index: int) -> bytes:
        if not self.protected:
            try:
                return self.groups_name(vtype, index)
            except IndexError:
                pass
        # protected / dangling reference: synthetic name like gfalist's "v1_2A"
        return ("v%X_%X" % (vtype, index)).encode("ascii")

    def groups_name(self, vtype, index):
        return self.idents[vtype][index]

    def lines(self):
        """Yield raw program lines (without the size word)."""
        pos = self.list_off
        left = self.list_len
        while left > 0:
            if pos + 2 > len(self.data):
                break
            size = struct.unpack_from(">H", self.data, pos)[0]
            if size < 2 or pos + size > len(self.data):
                raise GfaError("bad line size %d at offset %d" % (size, pos))
            yield self.data[pos + 2:pos + size]
            pos += size
            left -= size


# --------------------------------------------------------------------------
# Line decoder
# --------------------------------------------------------------------------
class Decoder:
    def __init__(self, prog: Program, bug_compat=False, verbose=False,
                 save_inline=None, inline_base="inline"):
        self.p = prog
        self.depth = 0
        self.bug_compat = bug_compat
        self.verbose = verbose
        self.save_inline = save_inline
        self.inline_base = inline_base
        self.lineno = 0
        self.inline_files = []
        self.warnings = []

    # -- helpers ----------------------------------------------------------
    def _indent(self, out, levels):
        if levels > 0:
            out += b"  " * levels

    def _var(self, out, vtype, index):
        out += self.p.var_name(vtype, index)
        out += VAR_SUFFIX[vtype]

    def decode(self, buf: bytes):
        """Return the text of one program line (bytes, list of strings for
        INLINE), or None for the end-of-program marker."""
        self.lineno += 1
        n = len(buf)
        if n < 2:
            return b""
        lcp = (buf[0] << 8) | buf[1]
        src = 2
        out = bytearray()

        # ---- indentation -------------------------------------------------
        if lcp in OPENERS:
            self._indent(out, self.depth)
            self.depth += 1
        elif lcp == FUNCTION_FOLDED:
            self._indent(out, self.depth)
            if not self.bug_compat:
                self.depth += 1
        elif lcp in CLOSERS:
            self.depth -= 1
            self._indent(out, self.depth)
        elif lcp in MIDDLES:
            self._indent(out, self.depth - 1)
        else:
            self._indent(out, self.depth)

        out += LCT.get(lcp & ~3, "").encode("latin-1")

        def at_eol_mark():
            return src < n and buf[src] == EOL_MARK

        # ---- command specific operands ----------------------------------
        if lcp in REM_LIKE or lcp in RAW_LINE:
            if lcp in REM_LIKE and src < n and buf[src] != 0x0D:
                out += b" "
            end = buf.find(b"\r", src)
            if end < 0:
                end = n
            out += buf[src:end]
            return bytes(out)
        if lcp == END_OF_PROGRAM:
            return None
        if lcp in SPACE_IF_ARGS:
            if src < n and not at_eol_mark():
                out += b" "
        elif lcp in VARCMD:
            vtype, tail, skip4 = VARCMD[lcp]
            if skip4:
                src += 4
            if src + 2 <= n:
                self._var(out, vtype, (buf[src] << 8) | buf[src + 1])
                src += 2
            out += tail
        elif lcp in PROC_DEFS:
            if src + 2 <= n:
                self._var(out, 11, (buf[src] << 8) | buf[src + 1])
                src += 2
            if not at_eol_mark():
                out += b"("
        elif lcp in SKIP4:
            src += 4

        # ---- token stream ------------------------------------------------
        while src < n:
            tok = buf[src]
            src += 1

            if tok == EOL_MARK:
                if src & 1:
                    src += 1            # align to a word boundary
                if src >= n:
                    break
                if lcp == INLINE:
                    return self._inline(out, buf[src:], lcp)
                spaces = buf[src]
                src += 1
                end = buf.find(b"\r", src)
                if end < 0:
                    end = n
                out += b" " * spaces + b"!" + buf[src:end]
                src = end + 1
                src += src & 1
                continue

            if tok in (198, 199):                # up to 4 chars as "ABCD"
                if tok == 199:
                    src += 1
                chunk = buf[src:src + 4]
                src += 4
                out += b'"' + chunk.lstrip(b"\x00") + b'"'
            elif tok in (200, 201):              # signed decimal long
                if tok == 201:
                    src += 1
                v = struct.unpack_from(">i", buf, src)[0]
                src += 4
                out += (b"-" if v < 0 else b"") + fmt_radix(abs(v), 10)
            elif tok in (202, 203, 204, 205, 206, 207):
                if tok & 1:
                    src += 1
                v = struct.unpack_from(">I", buf, src)[0]
                src += 4
                prefix, base = {202: (b"&H", 16), 204: (b"&O", 8),
                                206: (b"&X", 2)}[tok & ~1]
                out += prefix + fmt_radix(v, base)
            elif tok == 208:                     # secondary function token
                out += SFT.get(buf[src], "").encode("latin-1")
                src += 1
            elif tok in UNKNOWN_TOKENS:
                self.warnings.append("line %d: unknown token %d" %
                                     (self.lineno, tok))
                src += 1
            elif 215 <= tok <= 220:              # float constant shown as int
                if tok in (215, 217, 219):
                    src += 1
                d = gfa_float_to_double(buf[src:src + 8])
                src += 8
                prefix, base = {216: (b"&O", 8), 218: (b"&X", 2),
                                220: (b"&H", 16)}[tok + (tok & 1)]
                out += prefix + fmt_radix(to_int_trunc(d), base)
            elif tok in (221, 223):              # float constant
                if tok == 221:
                    src += 1
                d = gfa_float_to_double(buf[src:src + 8])
                src += 8
                out += fmt_double(d)
            elif tok == 222:                     # string literal
                ln = buf[src]
                src += 1
                out += b'"' + buf[src:src + ln].replace(b'"', b'""') + b'"'
                src += ln
            elif 224 <= tok <= 239:              # variable, 8 bit index
                self._var(out, tok - 224, buf[src])
                src += 1
            elif tok >= 240:                     # variable, 16 bit index
                self._var(out, tok - 240, (buf[src] << 8) | buf[src + 1])
                src += 2
            else:
                out += PFT.get(tok, "").encode("latin-1")
        return bytes(out)

    # -- INLINE data --------------------------------------------------------
    def _inline(self, out, data, lcp):
        """INLINE has raw binary after the argument tokens.  Keep the listing
        loadable: emit the data as comment lines (or save it to a file)."""
        lines = [bytes(out)]
        if self.save_inline is not None:
            name = self._inline_name(bytes(out))
            path = os.path.join(self.save_inline, name)
            with open(path, "wb") as f:
                f.write(data)
            self.inline_files.append((path, len(data)))
            lines.append(b"' ## INLINE data saved in " + name.encode("ascii") +
                         b" (%d bytes)" % len(data))
        else:
            lines.append(b"' ## INLINE data:")
            for off in range(0, len(data), 16):
                chunk = data[off:off + 16]
                lines.append(b"' $%04x: " % off +
                             b" ".join(b"%02x" % c for c in chunk))
            lines.append(b"' %d bytes." % len(data))
        return lines

    def _inline_name(self, text):
        word = text.strip()[len(b"INLINE "):].split(b",")[0].strip()
        stem = bytes(c if (48 <= c <= 57 or 65 <= c <= 90 or 97 <= c <= 122)
                     else 95 for c in word).decode("ascii") or "inline"
        base = "%s_%s" % (self.inline_base, stem) if self.inline_base else stem
        name = base + ".inl"
        used = {os.path.basename(p) for p, _ in self.inline_files}
        k = 2
        while name in used:
            name = "%s_%d.inl" % (base, k)
            k += 1
        return name


# --------------------------------------------------------------------------
# Conversion driver
# --------------------------------------------------------------------------
def convert(data: bytes, utf8=False, bug_compat=False, verbose=False,
            save_inline=None, inline_base="inline"):
    """Return (listing_bytes, decoder)."""
    prog = Program(data)
    dec = Decoder(prog, bug_compat, verbose, save_inline, inline_base)
    eol = b"\n" if utf8 else b"\r\n"
    chunks = []
    for raw in prog.lines():
        res = dec.decode(raw)
        if res is None:
            continue
        for text in ([res] if isinstance(res, bytes) else res):
            if utf8:
                text = st_to_utf8(text)
            chunks.append(text + eol)
    return b"".join(chunks), dec


def default_output(path: str) -> str:
    root, ext = os.path.splitext(path)
    return root + (".lst" if ext.islower() or not ext else ".LST")


def main(argv=None):
    ap = argparse.ArgumentParser(
        prog="gfa2lst",
        description="Convert tokenized GFA-BASIC 3.x (Atari ST) .GFA files to "
                    "ASCII .LST listings.")
    ap.add_argument("files", nargs="*", help="input .GFA file(s); '-' = stdin")
    ap.add_argument("-o", "--output", help="output file ('-' = stdout); only "
                    "valid with a single input")
    ap.add_argument("-d", "--outdir", help="write the .LST files into this "
                    "directory")
    ap.add_argument("-c", "--utf8", action="store_true",
                    help="convert the Atari ST character set to UTF-8 and use "
                         "LF line ends (default: raw ST bytes, CR/LF)")
    ap.add_argument("-i", "--save-inline", metavar="DIR",
                    help="save INLINE data as .inl files in DIR instead of "
                         "dumping it as comment lines")
    ap.add_argument("-b", "--bug-compat", action="store_true",
                    help="emulate GFA's own listing bug (no indent after "
                         "'> FUNCTION')")
    ap.add_argument("-v", "--verbose", action="store_true")
    ap.add_argument("-V", "--version", action="version",
                    version="gfa2lst " + VERSION)
    args = ap.parse_args(argv)

    if not args.files:
        ap.error("no input file")
    if args.output and len(args.files) > 1:
        ap.error("-o needs exactly one input file")

    rc = 0
    for path in args.files:
        try:
            if path == "-":
                data = sys.stdin.buffer.read()
            else:
                with open(path, "rb") as f:
                    data = f.read()
            inl_dir = args.save_inline
            if inl_dir:
                os.makedirs(inl_dir, exist_ok=True)
            base = os.path.splitext(os.path.basename(path))[0].lower() \
                if path != "-" else "inline"
            lst, dec = convert(data, args.utf8, args.bug_compat, args.verbose,
                               inl_dir, base)
        except (GfaError, OSError, struct.error) as e:
            print("gfa2lst: %s: %s" % (path, e), file=sys.stderr)
            rc = 1
            continue

        if args.output:
            dest = args.output
        elif path == "-":
            dest = "-"
        else:
            dest = default_output(path)
            if args.outdir:
                dest = os.path.join(args.outdir, os.path.basename(dest))
        if dest == "-":
            sys.stdout.buffer.write(lst)
        else:
            if args.outdir:
                os.makedirs(args.outdir, exist_ok=True)
            with open(dest, "wb") as f:
                f.write(lst)
        if args.verbose:
            print("gfa2lst: %s -> %s (%d lines)" %
                  (path, dest, lst.count(b"\n")), file=sys.stderr)
            for w in dec.warnings:
                print("gfa2lst: %s: warning: %s" % (path, w), file=sys.stderr)
            for p, ln in dec.inline_files:
                print("gfa2lst: INLINE saved: %s (%d bytes)" % (p, ln),
                      file=sys.stderr)
    return rc


if __name__ == "__main__":
    sys.exit(main())
